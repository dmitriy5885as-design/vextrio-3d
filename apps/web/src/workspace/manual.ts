export function describeFunction(label: string): string {
  const clean = label
    .replace(/\s*\([^)]*\)/g, "")
    .replace(/…/g, "")
    .trim();
  if (/Заблок|Разблок/i.test(clean))
    return "Блокировка защищает объект и его дочернюю геометрию от изменений. Разблокирование возвращает возможность редактировать.";
  if (/боковую панель/i.test(clean))
    return "Скрыть или вернуть структуру и свойства без изменения модели и выделения.";
  if (/навигатор/i.test(clean))
    return "Скрыть или вернуть куб ориентации и кнопки управления камерой. Значок возврата остаётся у края сцены.";
  if (/Сетка и оси/.test(clean))
    return "Показать или скрыть рабочую сетку и оси координат. Геометрия документа не изменяется.";
  if (/Стартовый экран/.test(clean))
    return "Вернуться к проектам, шаблонам и инструкциям. Текущий документ и история останутся доступны через Продолжить.";
  if (/Файл$/.test(clean))
    return "Создать, открыть, сохранить проект, импортировать модель или экспортировать геометрию.";
  if (/^Отменить$|^Повторить$/.test(clean))
    return manual.find((m) => m.name === "Отменить / повторить")!.description;
  if (/^Открыть$/.test(clean))
    return manual.find((m) => m.name === "Открыть проект")!.description;
  return (
    manual.find(
      (m) =>
        m.name === clean ||
        m.name.startsWith(clean) ||
        clean.startsWith(m.name),
    )?.description ??
    (label.includes("Создать:")
      ? "Добавить примитив в текущий документ. Его размеры и положение доступны в свойствах."
      : label.includes("Изометр")
        ? "Показать модель под углом к трём основным осям."
        : label.includes("проекц")
          ? "Переключить перспективную и ортографическую камеру без изменения модели."
          : "")
  );
}
